const {test}=require('node:test');
const assert=require('node:assert/strict');
const vm=require('node:vm');
const fs=require('node:fs');
const path=require('node:path');
test('architecture selection, future actions, filters and unknown deep links',()=>{
  const elements=new Map();
  const make=()=>({textContent:'',hidden:false,href:'',listeners:{},attrs:{},children:[],addEventListener(k,f){this.listeners[k]=f},setAttribute(k,v){this.attrs[k]=v},replaceChildren(...v){this.children=v},classList:{toggle(){}}});
  const buttons=['control','identity','portal','developer','contracts','observe','agents','gateway','cloud','ai','policy','limits','backend','accounting'].map(key=>Object.assign(make(),{dataset:{system:key,layer:['observe','policy','limits'].includes(key)?'future':'trust'}}));
  const views=['all','future'].map(key=>Object.assign(make(),{dataset:{view:key}}));
  for(const key of ['title','stage','goal','relation','evidence','capabilities','local','print'])elements.set('arch-'+key,make());
  const root={querySelectorAll:s=>s==='[data-system]'?buttons:views};
  const location={hash:'#system-observe'};const events={};let printed=false;
  const document={querySelector:()=>root,getElementById:id=>elements.get(id),createElement:make};
  const window={history:{replaceState(a,b,hash){location.hash=hash}},addEventListener(k,f){events[k]=f},print(){printed=true}};
  vm.runInNewContext(fs.readFileSync(path.join(__dirname,'../src/Fanasa.AccessManagement.Web/wwwroot/js/architecture.js'),'utf8'),{document,window,location});
  assert.equal(elements.get('arch-title').textContent,'دیده‌بانی خدمات');
  assert.equal(elements.get('arch-local').hidden,true);
  assert.equal(elements.get('arch-stage').textContent,'هدف');
  buttons[0].listeners.click();assert.equal(location.hash,'#system-control');
  assert.equal(elements.get('arch-local').href,'/Platform');assert.equal(elements.get('arch-local').hidden,false);
  assert.equal(elements.get('arch-capabilities').children.length,3);
  buttons.find(b=>b.dataset.system==='developer').listeners.click();
  assert.equal(elements.get('arch-stage').textContent,'پذیرش‌نشده');
  assert.match(elements.get('arch-evidence').textContent,/localhost فقط محیط توسعه/);
  assert.equal(elements.get('arch-local').href,'https://developer.fanasa.net.local/?workspace=studio&view=roadmap');
  buttons.find(b=>b.dataset.system==='policy').listeners.click();
  assert.match(elements.get('arch-relation').textContent,/PDP شمارنده یا بودجه را تغییر نمی‌دهد/);
  assert.match(elements.get('arch-evidence').textContent,/انطباق کامل پروفایل منتخب پذیرش نشده/);
  assert.equal(elements.get('arch-stage').textContent,'پذیرش‌نشده');
  buttons.find(b=>b.dataset.system==='limits').listeners.click();
  assert.match(elements.get('arch-relation').textContent,/نسخه تازه سیاست سهمیه را صفر نمی‌کند/);
  assert.match(elements.get('arch-evidence').textContent,/single-Gateway/);
  assert.equal(elements.get('arch-local').hidden,true);
  buttons.find(b=>b.dataset.system==='accounting').listeners.click();
  assert.equal(elements.get('arch-stage').textContent,'موجود');
  assert.match(elements.get('arch-evidence').textContent,/پذیرش مالی عملیاتی باقی/);
  views[1].listeners.click();assert.equal(location.hash,'#system-observe');
  location.hash='#system-unknown';events.hashchange();assert.equal(elements.get('arch-title').textContent,'دیده‌بانی خدمات');
  elements.get('arch-print').listeners.click();assert.equal(printed,true);
});
test('reference architecture contains planes, contract mapping and safe policy disclosures',()=>{
  const page=fs.readFileSync(path.join(__dirname,'../src/Fanasa.AccessManagement.Web/Pages/Architecture.cshtml'),'utf8');
  for(const marker of ['Control Plane','Data Plane','OASIS XACML','TPS و Burst','Eligibility','NotApplicable','Indeterminate','PDP بدون اثر جانبی','معماری هدف'])assert.ok(page.includes(marker),marker);
  for(const key of ['policy','limits','backend','accounting'])assert.ok(page.includes(`data-system="${key}"`),key);
  assert.match(page,/لینک‌ها از رجیستری مرکزی/);
  assert.doesNotMatch(page,/https:\/\/api\.fanasa\.net\.local/);
  assert.match(page,/۱۵ اکتبر ۲۰۲۶/);
  assert.match(page,/آزمون مصنوعی و smoke محدود جای پذیرش کامل عملیاتی/);
});
